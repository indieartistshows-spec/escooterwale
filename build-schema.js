const num = v => { const m = String(v).match(/[\d.]+/); return m ? parseFloat(m[0]) : undefined; };

function inject(file, graph) {
  let s = fs.readFileSync(file, 'utf8');
  const block = START + '\n<script type="application/ld+json">\n'
    + JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2)
    + '\n</script>\n' + END + '\n';
  const re = new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END + '\\n?');
  s = re.test(s) ? s.replace(re, block) : s.replace('</head>', block + '</head>');
  fs.writeFileSync(file, s);
  console.log('schema →', file);
}

